"""Reuse installed packages at install time, with no dependency on source paths."""
import argparse
import hashlib
import importlib.metadata as metadata
import os
import shutil
from pathlib import Path
try:
    from packaging.requirements import Requirement
    from packaging.utils import canonicalize_name
except ImportError:
    from pip._vendor.packaging.requirements import Requirement
    from pip._vendor.packaging.utils import canonicalize_name


def _digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream,'sha256').digest() if hasattr(hashlib,'file_digest') else _hash_stream(stream)


def _hash_stream(stream):
    value=hashlib.sha256()
    for chunk in iter(lambda:stream.read(1024*1024),b''):value.update(chunk)
    return value.digest()


def reuse(target,sources,requirements):
    target=Path(target).resolve();target.mkdir(parents=True,exist_ok=True)
    available={}
    for source in sources:
        source=Path(source).resolve()
        if source==target or not source.is_dir():continue
        for dist in metadata.distributions(path=[str(source)]):
            available.setdefault(canonicalize_name(dist.metadata['Name']),[]).append((source,dist))
    installed={canonicalize_name(dist.metadata['Name']):dist.version
               for dist in metadata.distributions(path=[str(target)])}
    visited=set();report={'reused':[],'skipped':[]}

    def copy(spec):
        requirement=Requirement(spec);name=canonicalize_name(requirement.name)
        if requirement.marker and not requirement.marker.evaluate({'extra':''}):return
        if name in visited:return
        visited.add(name)
        if name in installed:
            if installed[name] not in requirement.specifier:report['skipped'].append(str(requirement))
            return
        candidates=[(source,dist) for source,dist in available.get(name,[])
                    if dist.version in requirement.specifier and dist.files]
        if not candidates:report['skipped'].append(str(requirement));return
        for source,dist in candidates:
            pairs=[];valid=True
            for entry in dist.files:
                original=source/str(entry);destination=target/str(entry)
                # Entry points outside site-packages are regenerated by pip if needed.
                if source not in original.resolve().parents or target not in destination.resolve().parents:
                    if '..' in entry.parts:continue
                    valid=False;break
                if '__pycache__' in entry.parts:continue
                if any(parent.is_symlink() for parent in [original,*original.parents] if parent!=source):
                    valid=False;break
                if not original.is_file():valid=False;break
                if destination.exists() and (not destination.is_file() or _digest(original)!=_digest(destination)):
                    valid=False;break
                pairs.append((original,destination))
            if not valid or not pairs:continue
            for original,destination in pairs:
                if destination.exists():continue
                destination.parent.mkdir(parents=True,exist_ok=True)
                try:os.link(original,destination)
                except OSError:shutil.copy2(original,destination)
            report['reused'].append(name);installed[name]=dist.version
            for dependency in dist.requires or []:copy(dependency)
            return
        report['skipped'].append(str(requirement))

    for line in requirements:
        line=line.strip()
        if line and not line.startswith('#'):copy(line)
    return report


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--target',required=True,type=Path)
    parser.add_argument('--source',action='append',type=Path,default=[])
    parser.add_argument('--requirements',required=True,type=Path)
    options=parser.parse_args()
    result=reuse(options.target,options.source,options.requirements.read_text().splitlines())
    print(f"Reused {len(result['reused'])} packages; pip will resolve {len(result['skipped'])} packages.")
